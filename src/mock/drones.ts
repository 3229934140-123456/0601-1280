export const generateFlightPath = (centerLat: number, centerLng: number, points: number = 20) => {
  const path = [];
  for (let i = 0; i < points; i++) {
    path.push({
      lat: centerLat + (Math.random() - 0.5) * 0.01,
      lng: centerLng + (Math.random() - 0.5) * 0.01,
      time: new Date(Date.now() - (points - i) * 60000).toISOString(),
    });
  }
  return path;
};
